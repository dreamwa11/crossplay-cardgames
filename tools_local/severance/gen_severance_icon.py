#!/usr/bin/env python3
"""Regenerate src/apps_local/severance/SeveranceShelfIcon.h from art/shelf.svg."""
import io
import os
import subprocess

import numpy as np
from PIL import Image

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ART = os.path.join(REPO, "src/apps_local/severance/art/shelf.svg")
OUT = os.path.join(REPO, "src/apps_local/severance/SeveranceShelfIcon.h")
png = subprocess.run(["rsvg-convert", "-w", "32", "-h", "32", ART], capture_output=True, check=True).stdout
img = Image.open(io.BytesIO(png)).convert("RGBA")
bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
bg.paste(img, mask=img.split()[3])
ink = np.array(bg.convert("L")) < 128
data = np.packbits(~ink, axis=1).flatten()
with open(OUT, "w") as f:
    f.write("#pragma once\n\n// Generated by tools_local/severance/gen_severance_icon.py. Do not edit.\n\n#include \"Icon.h\"\n\n")
    f.write("static const uint8_t icon_severance_32_bits[] = {" + ",".join(f"0x{b:02X}" for b in data) + "};\n")
    f.write("static const freeink::Icon icon_severance_32 = {32, 32, 16, icon_severance_32_bits};\n")
print("wrote", OUT)
