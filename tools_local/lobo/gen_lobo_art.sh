#!/bin/bash
# Regenerate src/apps_local/lobo/LoboArt.h: the suits (48, 64, 96px), the small
# marks (24, 32px), the Wolf in two sizes (an opaque silhouette and the ink on
# top), his hat, and the cellar behind him. Needs rsvg-convert, Pillow, numpy.
set -euo pipefail
REPO="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../.." && pwd)"
cd "$REPO"
ART=src/apps_local/lobo/art
OUT=src/apps_local/lobo/LoboArt.h
GEN=freeink-sdk/libs/assets/Icons/tools/gen_icons.py
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
python3 "$GEN" --manifest "$ART/icons.txt" --svgdir "$ART" --sizes 48,64,96 --out "$TMP/suits.h" >/dev/null
python3 "$GEN" --manifest "$ART/marks.txt" --svgdir "$ART" --sizes 24,32 --out "$TMP/marks.h" >/dev/null
python3 tools_local/scoundrel/draw_rooms.py cellar "$TMP/cellar.svg" 230
rsvg-convert "$TMP/cellar.svg" -o "$TMP/cellar.png"
python3 - "$ART/wolf.webp" "$TMP" <<'PY'
import sys
import numpy as np
from PIL import Image, ImageOps, ImageFilter
src, tmp = sys.argv[1], sys.argv[2]
out = []

def emit(name, white):
    """white: bool array, True = leave the pixel. Writes a freeink::Icon."""
    h, w = white.shape
    data = []
    for y in range(h):
        for bx in range(0, w, 8):
            b = 0
            for k in range(8):
                x = bx + k
                b = (b << 1) | (1 if x >= w or white[y, x] else 0)
            data.append(b)
    out.append(f'static const uint8_t {name}_bits[] = {{' + ','.join(f'0x{b:02X}' for b in data) + '};')
    out.append(f'static const freeink::Icon {name} = {{{w}, {h}, {h // 2}, {name}_bits}};')

def ink(img, H):
    """The portrait as an engraving: sharpened, error-diffused, outlined."""
    W = round(img.width * H / img.height)
    s = img.resize((W, H), Image.LANCZOS)
    alpha = np.array(s.split()[3]) > 128
    g = ImageOps.autocontrast(s.convert('L'), cutoff=1).filter(ImageFilter.UnsharpMask(2, 220, 1))
    v = np.clip((np.array(g).astype(float) / 255) ** 0.8 + 0.1, 0, 1)
    white = np.array(Image.fromarray((v * 255).astype('uint8')).convert('1', dither=Image.FLOYDSTEINBERG)) > 0
    inner = np.array(Image.fromarray((alpha * 255).astype('uint8')).filter(ImageFilter.MinFilter(3))) > 128
    white[alpha & ~inner] = False
    white[~alpha] = True
    return alpha, white

wolf = Image.open(src).convert('RGBA')
for name, H in (('wolf_small', 250), ('wolf_big', 360)):
    alpha, white = ink(wolf, H)
    emit(name + '_mask', ~alpha)      # drawn in white first, so nothing shows through him
    emit(name + '_ink', white)

# His hat, cut from the top of the same picture: the crown and the dark brim.
hat = wolf.crop((0, 0, wolf.width, 168))
lum = np.array(hat.convert('L')).astype(float) / 255
a = np.array(hat.split()[3]) > 128
rows = np.arange(hat.height)[:, None]
keep = a & ((rows < 140) | (lum < 0.42))
keep = np.array(Image.fromarray((keep * 255).astype('uint8')).filter(ImageFilter.MedianFilter(5))) > 128
hat.putalpha(Image.fromarray((keep * 255).astype('uint8')))
bbox = Image.fromarray((keep * 255).astype('uint8')).getbbox()
hat = hat.crop(bbox).rotate(-8, resample=Image.BICUBIC, expand=True)
alpha, white = ink(hat, 120)
emit('wolf_hat_mask', ~alpha)
emit('wolf_hat_ink', white)

# The cellar behind him, at half strength like Scoundrel's rooms.
c = Image.open(f'{tmp}/cellar.png').convert('RGBA')
bg = Image.new('RGBA', c.size, 'white'); bg.alpha_composite(c)
g = np.array(bg.convert('L')) < 128
yy, xx = np.mgrid[0:g.shape[0], 0:g.shape[1]]
emit('lobo_backdrop', ~(g & ((xx + yy) % 2 == 0)))
# A fade for cards that cannot join the current pick: every other pixel,
# drawn in white over a table card (86x124).
yy, xx = np.mgrid[0:124, 0:86]
emit('lobo_fade', (xx + yy) % 2 == 1)
open(f'{tmp}/pictures.h', 'w').write('\n'.join(out) + '\n')
PY
{
  printf '#pragma once\n\n'
  printf '// Lobo artwork. Generated by tools_local/lobo/gen_lobo_art.sh; do not edit.\n'
  printf '// Icons: game-icons.net (CC BY 3.0). The Wolf: the phone version'"'"'s portrait\n'
  printf '// (FLUX.1 Krea), converted to black and white. See art/ATTRIBUTION.md.\n\n'
  sed '/^#pragma once$/d;s|// Generated by libs/assets/Icons/tools/gen_icons.py from Lucide SVGs. Do not edit.||' "$TMP/suits.h"
  sed '/^#pragma once$/d;/#include "Icon.h"/d;s|// Generated by libs/assets/Icons/tools/gen_icons.py from Lucide SVGs. Do not edit.||' "$TMP/marks.h"
  cat "$TMP/pictures.h"
} > "$OUT"
echo "wrote $OUT"
SHELF=src/apps_local/lobo/LoboShelfIcon.h
printf 'wolf = wolf\n' > "$TMP/shelf.txt"
python3 "$GEN" --manifest "$TMP/shelf.txt" --svgdir "$ART" --sizes 32 --out "$SHELF" >/dev/null
sed -i 's|// Generated by libs/assets/Icons/tools/gen_icons.py from Lucide SVGs. Do not edit.|// The Lobo shelf icon (game-icons wolf head). Generated by tools_local/lobo/gen_lobo_art.sh.|;s/icon_wolf_32/icon_lobo_32/g;s/icon_wolf_32_bits/icon_lobo_32_bits/g' "$SHELF"
echo "wrote $SHELF"
