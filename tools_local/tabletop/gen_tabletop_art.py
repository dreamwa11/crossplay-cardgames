#!/usr/bin/env python3
"""Regenerate src/apps_local/tabletop/TabletopArt.h from the SVGs in art/.

    python3 tools_local/tabletop/gen_tabletop_art.py

Needs rsvg-convert, Pillow and numpy. The game-icons.net SVGs are white
glyphs on a black square; they are inverted here so every icon is ink on
paper. Hearts and diamonds are drawn as outlines, the e-ink stand-in for red.
Pictures that can be drawn reversed (tarot) also get a copy turned 180
degrees, because the renderer does not rotate bitmaps.
"""
import io
import os
import subprocess
import sys

import numpy as np
from PIL import Image, ImageFilter

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ART = os.path.join(REPO, "src/apps_local/tabletop/art")
OUT = os.path.join(REPO, "src/apps_local/tabletop/TabletopArt.h")


def raster(name, px):
    png = subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), os.path.join(ART, name + ".svg")],
                         capture_output=True, check=True).stdout
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
    bg.paste(img, mask=img.split()[3])
    lum = np.array(bg.convert("L"))
    ink = lum < 110
    if ink[0, 0] and ink[0, -1] and ink[-1, 0]:  # a game-icons square: the glyph is the white part
        ink = ~ink
    return ink


def outline(ink, px):
    w = max(2, round(px / 18))
    im = Image.fromarray((ink * 255).astype("uint8")).filter(ImageFilter.MinFilter(2 * w + 1))
    return ink & ~(np.array(im) > 128)


out = ["#pragma once", "", "// Generated by tools_local/tabletop/gen_tabletop_art.py. Do not edit.", "",
       '#include "Icon.h"', ""]
total = 0


def emit(cname, ink):
    global total
    h, w = ink.shape
    data = []
    for y in range(h):
        for bx in range(0, w, 8):
            b = 0
            for k in range(8):
                x = bx + k
                b = (b << 1) | (0 if x < w and ink[y, x] else 1)
            data.append(b)
    total += len(data)
    out.append(f"static const uint8_t {cname}_bits[] = {{" + ",".join(f"0x{b:02X}" for b in data) + "};")
    out.append(f"static const freeink::Icon {cname} = {{{w}, {h}, {h // 2}, {cname}_bits}};")


def icon(name, sizes, turned=(), hollow=False, cname=None):
    for px in sizes:
        ink = raster(name, px)
        if hollow:
            ink = outline(ink, px)
        emit(f"icon_tt_{cname or name}_{px}", ink)
        if px in turned:
            emit(f"icon_tt_{cname or name}_{px}_r", ink[::-1, ::-1])


for n in range(22):
    icon(f"major_{n:02d}", (128, 88, 48), turned=(128, 88))
for s in ("wands", "cups", "swords", "pentacles"):
    icon(s, (128, 64, 40), turned=(128, 64))
for s in ("spades", "clubs"):
    icon(s, (96, 40, 24))
for s in ("hearts", "diamonds"):
    icon(s, (96, 40, 24), hollow=True)
icon("joker", (96, 40))
# The Pale Motel's three card backs (diamonds, chevrons, rays), its red as
# paper. Each at the sizes a back is drawn, cropped to fill like CSS cover.
def cover(name, w, h):
    sh = round(w * 130 / 92)
    if sh >= h:
        png = subprocess.run(["rsvg-convert", "-w", str(w), "-h", str(sh), os.path.join(ART, name + ".svg")],
                             capture_output=True, check=True).stdout
        top, left = (sh - h) // 2, 0
    else:
        sw = round(h * 92 / 130)
        png = subprocess.run(["rsvg-convert", "-w", str(sw), "-h", str(h), os.path.join(ART, name + ".svg")],
                             capture_output=True, check=True).stdout
        top, left = 0, (sw - w) // 2
    img = Image.open(io.BytesIO(png)).convert("L")
    return np.array(img)[top:top + h, left:left + w] < 110


# The playing deck wears 0 or 1 (on its screen and its menu tile), tarot 2.
for n, sizes in ((0, ((224, 318), (70, 104))), (1, ((224, 318), (70, 104))), (2, ((224, 348),))):
    for (w, h) in sizes:
        emit(f"icon_tt_back{n}_{w}x{h}", cover(f"back{n}", w, h))
for d in ("d4", "d6", "d8", "d10", "d12", "d20", "d100"):
    icon(d, (96, 48))

open(OUT, "w").write("\n".join(out) + "\n")

# The shelf mark, in its own header so Shelf.cpp does not pull in the deck.
out = ["#pragma once", "", "// Generated by tools_local/tabletop/gen_tabletop_art.py. Do not edit.", "",
       '#include "Icon.h"', ""]
emit("icon_tabletop_32", raster("shelf_small", 32))
open(OUT.replace("TabletopArt.h", "TabletopShelfIcon.h"), "w").write("\n".join(out) + "\n")
print(f"wrote {OUT}: {total} bytes of bitmaps", file=sys.stderr)
